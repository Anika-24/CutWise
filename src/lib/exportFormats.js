export function sanitizeFileName(value = 'cutwise_plan') {
  const safe = String(value || 'cutwise_plan')
    .trim()
    .replace(/[^a-zA-Z0-9._-]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 80);

  return safe || 'cutwise_plan';
}

export function buildExportBundle(projectName, material = {}, layout = {}, pieces = []) {
  const normalizedMaterial = {
    ...material,
    sheetWidth: Number(material?.sheetWidth ?? 0),
    sheetHeight: Number(material?.sheetHeight ?? 0),
    thickness: Number(material?.thickness ?? 0),
    sheetQuantity: Number(material?.sheetQuantity ?? 0),
    pricePerSheet: Number(material?.pricePerSheet ?? 0),
    kerf: Number(material?.kerf ?? 0),
    edgeMargin: Number(material?.edgeMargin ?? 0),
  };

  return {
    projectName: projectName || 'CutWise Project',
    exportedAt: new Date().toISOString(),
    material: normalizedMaterial,
    layout: {
      valid: Boolean(layout?.valid),
      status: layout?.status || 'unknown',
      strategy: layout?.strategy || 'unknown',
      algorithm: layout?.algorithm || 'unknown',
      stats: layout?.stats || {},
      sheets: (layout?.sheets || []).map((sheet, index) => ({
        index: sheet?.index ?? index,
        width: Number(sheet?.width ?? 0),
        height: Number(sheet?.height ?? 0),
        placements: (sheet?.placements || []).map((placement) => ({
          name: placement?.name || 'Piece',
          x: Number(placement?.x ?? 0),
          y: Number(placement?.y ?? 0),
          w: Number(placement?.w ?? 0),
          h: Number(placement?.h ?? 0),
          rotated: Boolean(placement?.rotated),
          sheet: Number(sheet?.index ?? index) + 1,
        })),
      })),
      unplaced: layout?.unplaced || [],
    },
    pieces: Array.isArray(pieces) ? pieces.map((piece) => ({ ...piece })) : [],
  };
}

function escapeCsv(value) {
  return String(value ?? '').replace(/\r?\n/g, ' ').replace(/"/g, '""');
}

function flattenPlacements(layout) {
  return (layout?.sheets || []).flatMap((sheet, sheetIndex) =>
    (sheet?.placements || []).map((placement) => ({
      sheetIndex: sheet?.index ?? sheetIndex,
      ...placement,
    })),
  );
}

export function generateCsvExport(projectName, material, layout) {
  const rows = [
    ['Project', projectName],
    ['Material', material?.type || 'Unknown'],
    ['Sheet Width', material?.sheetWidth ?? ''],
    ['Sheet Height', material?.sheetHeight ?? ''],
    ['Thickness', material?.thickness ?? ''],
    ['Kerf', material?.kerf ?? ''],
    ['Edge Margin', material?.edgeMargin ?? ''],
    [''],
    ['pieceName', 'sheetIndex', 'x', 'y', 'width', 'height', 'rotated'],
  ];

  for (const placement of flattenPlacements(layout)) {
    rows.push([
      placement.name || 'Piece',
      Number(placement.sheetIndex ?? 0),
      Number(placement.x ?? 0),
      Number(placement.y ?? 0),
      Number(placement.w ?? 0),
      Number(placement.h ?? 0),
      Boolean(placement.rotated) ? 'true' : 'false',
    ]);
  }

  return rows
    .map((row) => row.map((cell) => escapeCsv(cell)).join(','))
    .join('\n');
}

export function generateLaserSvgExport(projectName, material, layout) {
  const sheets = layout?.sheets || [];
  const width = Number(material?.sheetWidth || sheets[0]?.width || 0);
  const height = Number(material?.sheetHeight || sheets[0]?.height || 0);

  const body = sheets
    .map((sheet, sheetIndex) => {
      const placements = sheet?.placements || [];
      const rects = placements
        .map((placement) => {
          const x = Number(placement?.x ?? 0);
          const y = Number(placement?.y ?? 0);
          const w = Number(placement?.w ?? 0);
          const h = Number(placement?.h ?? 0);
          const label = escapeXml(String(placement?.name || `Piece ${sheetIndex + 1}`));
          return `
            <g>
              <rect x="${x}" y="${y}" width="${w}" height="${h}" fill="none" stroke="#111827" stroke-width="1.4" />
              <text x="${x + 8}" y="${y + 16}" font-size="12" fill="#111827">${label}</text>
            </g>`;
        })
        .join('');

      return `
        <g id="sheet-${sheetIndex + 1}">
          <rect x="0" y="0" width="${sheet.width || width}" height="${sheet.height || height}" fill="#ffffff" stroke="#94a3b8" stroke-width="2" />
          ${rects}
        </g>`;
    })
    .join('');

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${width}mm" height="${height}mm" viewBox="0 0 ${width} ${height}">
  <title>${escapeXml(projectName || 'CutWise laser cut')}</title>
  <desc>Laser cut export generated by CutWise.</desc>
  ${body}
</svg>`;
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function generateCncProgram(projectName, material, layout) {
  const lines = [
    `; CutWise CNC export`,
    `; Project: ${projectName || 'CutWise Project'}`,
    `; Material: ${material?.type || 'Unknown'}`,
    'G21',
    'G90',
    'M3',
    '',
  ];

  for (const [sheetIndex, sheet] of (layout?.sheets || []).entries()) {
    lines.push(`; Sheet ${sheetIndex + 1}`);
    const placements = sheet?.placements || [];
    for (const placement of placements) {
      const x = Number(placement?.x ?? 0);
      const y = Number(placement?.y ?? 0);
      const w = Number(placement?.w ?? 0);
      const h = Number(placement?.h ?? 0);
      const name = String(placement?.name || `Piece ${sheetIndex + 1}`);
      lines.push(`; ${name}`);
      lines.push(`G0 X${x} Y${y}`);
      lines.push(`G1 X${x + w} Y${y}`);
      lines.push(`G1 X${x + w} Y${y + h}`);
      lines.push(`G1 X${x} Y${y + h}`);
      lines.push(`G1 X${x} Y${y}`);
      lines.push('');
    }
  }

  lines.push('M5');
  return lines.join('\n');
}

export function generateObjExport(projectName, material, layout) {
  const lines = [
    `# CutWise 3D machine export`,
    `# Project: ${projectName || 'CutWise Project'}`,
    `o ${sanitizeFileName(projectName || 'cutwise_project')}`,
  ];

  const thickness = Number(material?.thickness ?? 18) || 18;
  let nextVertexIndex = 1;

  const addPiece = (placement, sheetIndex) => {
    const x = Number(placement?.x ?? 0);
    const y = Number(placement?.y ?? 0);
    const w = Number(placement?.w ?? 0);
    const h = Number(placement?.h ?? 0);
    const vertices = [
      [x, y, 0],
      [x + w, y, 0],
      [x + w, y + h, 0],
      [x, y + h, 0],
      [x, y, thickness],
      [x + w, y, thickness],
      [x + w, y + h, thickness],
      [x, y + h, thickness],
    ];

    for (const [vx, vy, vz] of vertices) {
      lines.push(`v ${vx} ${vy} ${vz}`);
    }

    const faces = [
      [0, 1, 2, 3],
      [4, 5, 6, 7],
      [0, 1, 5, 4],
      [1, 2, 6, 5],
      [2, 3, 7, 6],
      [3, 0, 4, 7],
    ];

    const baseIndex = nextVertexIndex;
    nextVertexIndex += 8;

    for (const face of faces) {
      const faceIndices = face.map((offset) => baseIndex + offset).join(' ');
      lines.push(`f ${faceIndices}`);
    }
  };

  for (const [sheetIndex, sheet] of (layout?.sheets || []).entries()) {
    for (const placement of sheet?.placements || []) {
      addPiece(placement, sheetIndex);
    }
  }

  return lines.join('\n');
}

export function buildMachineExportBundle(projectName, material, layout, pieces = []) {
  return buildExportBundle(projectName, material, layout, pieces);
}
